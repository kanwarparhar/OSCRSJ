#!/usr/bin/env node
// Generates lib/finder/sjrData.ts from the Session-92 Scimago manifest.
//
// WHY A GENERATOR AND NOT A HAND-WRITTEN TABLE. Every SJR number in the product
// must be traceable to a source we already verified. `docs/formatting-expansion/
// manifest.json` is that source: it is the Scimago pull recorded on 2026-07-12
// when the registry went 14 -> 75. Typing 75 numbers by hand would introduce a
// transcription channel with no provenance and no way to re-verify. This script
// copies rank / sjr / quartile VERBATIM and nulls anything the manifest does not
// carry. It never computes, rounds, or infers a value.
//
// Deterministic by construction: entries are emitted sorted by slug, so re-running
// on an unchanged manifest produces a byte-identical file.
//
// Usage: npm run generate:sjr

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const MANIFEST_PATH = join(ROOT, 'docs/formatting-expansion/manifest.json')
const JOURNALS_DIR = join(ROOT, 'lib/formatting/journals')
const OUT_PATH = join(ROOT, 'lib/finder/sjrData.ts')

/** Provenance string stamped on every row sourced from the manifest. */
const SOURCE = 'scimago-manifest-2026-07-12'
const CATEGORY = 'Orthopedics and Sports Medicine'
const CATEGORY_SIZE = 341

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'))

/** Registry slugs = the rule-file basenames (README.md is not a journal). */
const registrySlugs = readdirSync(JOURNALS_DIR)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort()

/** Manifest rows keyed by slug. Journals not in the registry are ignored. */
const byslug = new Map()
for (const j of manifest.journals ?? []) {
  if (j && typeof j.slug === 'string') byslug.set(j.slug, j)
}

const year = manifest.sjr_year ?? null

const rows = []
const missing = []

for (const slug of registrySlugs) {
  const m = byslug.get(slug)
  if (!m) {
    // Should not happen — all 75 registry slugs are present in the manifest.
    // Emit an honest all-null row rather than silently dropping the journal.
    missing.push(slug)
    rows.push({
      slug,
      categoryRank: null,
      sjr: null,
      quartile: null,
      year: null,
      source: 'not-in-manifest',
    })
    continue
  }
  // A manifest row with rank: null (jocr outside the top-100 capture, oscrsj
  // unranked/new) carries no standing at all. Partial rows are corrupt, so a
  // null rank nulls the whole standing rather than keeping an orphan sjr.
  const ranked = m.rank !== null && m.rank !== undefined
  rows.push({
    slug,
    categoryRank: ranked ? m.rank : null,
    sjr: ranked ? (m.sjr ?? null) : null,
    quartile: ranked ? (m.quartile ?? null) : null,
    year: ranked ? year : null,
    source: SOURCE,
  })
}

const lit = (v) => (v === null ? 'null' : typeof v === 'string' ? `'${v}'` : String(v))

const body = rows
  .map(
    (r) =>
      `  '${r.slug}': { categoryRank: ${lit(r.categoryRank)}, sjr: ${lit(r.sjr)}, ` +
      `quartile: ${lit(r.quartile)}, year: ${lit(r.year)}, source: ${lit(r.source)} },`
  )
  .join('\n')

const out = `// DO NOT EDIT — generated by scripts/generate-sjr-data.mjs
//
// SJR standing for every registry journal, copied verbatim from the Session-92
// Scimago pull at docs/formatting-expansion/manifest.json (category
// '${CATEGORY}', id 2732; ${CATEGORY_SIZE} journals total;
// metrics based on Scopus data as of March 2026). Regenerate with
// \`npm run generate:sjr\` — never hand-edit this file.
//
// WHY SJR AND NOT IMPACT FACTOR. Journal Impact Factor is Clarivate-proprietary
// and may not be redistributed in this product. SJR is Scimago's freely licensed
// indicator. Do not add an IF field, ever.
//
// UNRANKED JOURNALS. A slug whose manifest row carries \`rank: null\` (jocr, which
// sits outside the top-100 capture, and oscrsj, which is new and unranked) gets
// an all-null standing. That is a real absence of data, not a zero: consumers
// must render it as "Not SJR-ranked" and must never sort it as if it were last
// on merit.

export interface SjrStanding {
  /** Rank within Scimago category '${CATEGORY}' (${CATEGORY_SIZE} journals). */
  categoryRank: number | null
  /** SJR score (Scimago Journal Rank indicator). */
  sjr: number | null
  quartile: 'Q1' | 'Q2' | 'Q3' | 'Q4' | null
  /** SJR data year per the manifest. */
  year: number | null
  /** Provenance: '${SOURCE}'. */
  source: string
}

export const SJR_CATEGORY = '${CATEGORY}'
export const SJR_CATEGORY_SIZE = ${CATEGORY_SIZE}

/** Standing for a slug the registry knows nothing about. */
export const NULL_SJR_STANDING: SjrStanding = {
  categoryRank: null,
  sjr: null,
  quartile: null,
  year: null,
  source: 'unknown-slug',
}

export const SJR_DATA: Record<string, SjrStanding> = {
${body}
}
`

writeFileSync(OUT_PATH, out, 'utf8')

const ranked = rows.filter((r) => r.categoryRank !== null).length
console.log(`generate:sjr — wrote ${rows.length} rows (${ranked} ranked, ${rows.length - ranked} unranked) to lib/finder/sjrData.ts`)
if (missing.length) {
  console.warn(`WARNING: ${missing.length} registry slug(s) missing from the manifest: ${missing.join(', ')}`)
}
